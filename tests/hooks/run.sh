#!/usr/bin/env bash
# Tests of the shared pre-commit hooks (hooks/). Run from the repository root:
#   bash tests/hooks/run.sh
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
work="$(mktemp -d)"
trap 'rm -rf "${work}"' EXIT
failures=0

expect() {
  local want="$1" name="$2"
  shift 2
  if "$@" > /dev/null 2>&1; then got=pass; else got=fail; fi
  if [[ "${got}" == "${want}" ]]; then
    echo "ok   ${name}"
  else
    echo "FAIL ${name}: expected ${want}, got ${got}"
    failures=$((failures + 1))
  fi
}

message() {
  printf '%s\n' "$@" > "${work}/COMMIT_EDITMSG"
  echo "${work}/COMMIT_EDITMSG"
}

hook="${root}/hooks/no-ai-attribution.sh"
expect pass "plain conventional message" "${hook}" "$(message 'feat(api): add the endpoint' '' 'Body text.')"
expect pass "human co-author" "${hook}" "$(message 'fix: typo' '' 'Co-Authored-By: Jane Doe <jane@example.org>')"
expect pass "commented trailer is ignored" "${hook}" "$(message 'fix: typo' '# Co-Authored-By: Claude <noreply@anthropic.com>')"
expect fail "claude co-author trailer" "${hook}" "$(message 'fix: typo' '' 'Co-Authored-By: Claude <noreply@anthropic.com>')"
expect fail "lower-case copilot trailer" "${hook}" "$(message 'fix: typo' '' 'co-authored-by: Copilot <copilot@github.com>')"
expect fail "generated with footer" "${hook}" "$(message 'fix: typo' '' 'Generated with Claude Code')"
expect fail "generated by footer" "${hook}" "$(message 'fix: typo' '' 'generated by ChatGPT')"

hook="${root}/hooks/sops-encrypted.sh"
cat > "${work}/clear.sops.yaml" <<'YAML'
apiVersion: v1
kind: Secret
stringData:
  password: hunter2
YAML
cat > "${work}/encrypted.sops.yaml" <<'YAML'
apiVersion: v1
kind: Secret
stringData:
  password: ENC[AES256_GCM,data:AAAA,iv:BBBB,tag:CCCC,type:str]
sops:
  age:
    - recipient: age1example
  lastmodified: "2026-01-01T00:00:00Z"
  mac: ENC[AES256_GCM,data:DDDD,iv:EEEE,tag:FFFF,type:str]
  version: 3.13.3
YAML
expect pass "encrypted sops file" "${hook}" "${work}/encrypted.sops.yaml"
expect fail "clear-text sops file" "${hook}" "${work}/clear.sops.yaml"
expect fail "one clear file among encrypted ones" "${hook}" "${work}/encrypted.sops.yaml" "${work}/clear.sops.yaml"

# The fixture of the kubernetes-manifests workflow must keep passing the hook.
expect pass "kustomize fixture secret" "${hook}" "${root}/tests/fixtures/kustomize/overlays/ci/secret.sops.yaml"

if ((failures)); then
  echo "${failures} hook test(s) failed"
  exit 1
fi
echo "All hook tests passed."
